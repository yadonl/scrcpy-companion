#!/usr/bin/env bash
# web/run.sh - 一条命令把「iPhone 能打开的安卓投屏网页端」跑起来
#
#   ./web/run.sh setup         首次安装（拉 ws-scrcpy、构建、生成证书与令牌）
#   ./web/run.sh start|stop|restart|status|url|logs
#
# 产物：
#   web/ws-scrcpy/     网页端本体（上游 NetrisTV/ws-scrcpy）
#   web/certs/         自签证书（Safari 要求 HTTPS 才有 WebCodecs）
#   web/ws-config.yaml ws-scrcpy 的端口配置（由 .env 生成）
#   web/.env           端口 / 令牌 / 上游地址
#   web/logs/          两个进程的日志
#
# 拓扑：iPhone ──https:9443（gate.js，要令牌）──> 127.0.0.1:8000（ws-scrcpy）
# ws-scrcpy 自己不做鉴权，所以它只能听回环；LAN 上唯一入口是 gate。
set -uo pipefail
cd "$(dirname "$0")" || exit 1
APP="$(pwd)"
ENVF="$APP/.env"
WSREPO="$APP/ws-scrcpy"
WSCONF="$APP/ws-config.yaml"
UPSTREAM_PORT="${UPSTREAM_PORT:-8000}"
GATE_PORT="${GATE_PORT:-9443}"
NODE_BIN="${NODE_BIN:-node}"
CERT_DAYS="${CERT_DAYS:-397}"

log() { printf '%s %s\n' "$(date '+%F %T')" "$*"; }
die() { printf 'x %s\n' "$*" >&2; exit 1; }

need_node() {
  command -v "$NODE_BIN" >/dev/null 2>&1 || die "需要 Node.js 18/20/22（找不到 $NODE_BIN）"
  local v; v=$("$NODE_BIN" -v | tr -d 'v' | cut -d. -f1)
  [ "$v" -ge 18 ] || die "Node 版本太低：$("$NODE_BIN" -v)，需要 >=18"
  [ "$v" -le 22 ] || log "警告：Node $v 偏新，ws-scrcpy 的原生模块可能编不过，建议 20 LTS"
}

# ws-scrcpy 依赖 node-pty（原生模块），没有预编译包时要用 node-gyp 现场编
need_toolchain() {
  local missing=""
  command -v python3 >/dev/null 2>&1 || missing="$missing python3"
  command -v make    >/dev/null 2>&1 || missing="$missing make"
  { command -v g++ >/dev/null 2>&1 || command -v cc >/dev/null 2>&1; } || missing="$missing g++/build-essential"
  if [ -n "$missing" ]; then
    cat >&2 <<EOF
x 缺少构建 node-pty 需要的工具：$missing

  Debian/Ubuntu（含飞牛 NAS）：sudo apt-get install -y build-essential python3
  Alpine：apk add --no-cache build-base python3
  macOS：xcode-select --install

  装完再跑一次 ./run.sh setup
EOF
    exit 1
  fi
}

# 本机局域网 IP。Linux 用 ip，macOS 没有 ip 也没有 hostname -I，只能 ipconfig。
lan_ip() {
  local ip=""
  if command -v ip >/dev/null 2>&1; then
    ip=$(ip route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')
  fi
  if [ -z "$ip" ]; then ip=$(hostname -I 2>/dev/null | awk '{print $1}'); fi
  if [ -z "$ip" ] && command -v ipconfig >/dev/null 2>&1; then
    ip=$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null)
  fi
  [ -n "$ip" ] || ip="127.0.0.1"
  printf '%s' "$ip"
}

# 证书要重签的三种情况：没有 / 快过期 / 本机 IP 变了（SAN 里没有新 IP）
cert_stale() {
  local ip="$1" cert="$APP/certs/cert.pem"
  [ -f "$cert" ] || return 0
  openssl x509 -checkend 604800 -noout -in "$cert" >/dev/null 2>&1 || return 0
  [ "$(cat "$APP/certs/.san_ip" 2>/dev/null)" = "$ip" ] || return 0
  return 1
}

gen_cert() {
  command -v openssl >/dev/null 2>&1 || die "需要 openssl >=1.1.1"
  local ip; ip=$(lan_ip)
  mkdir -p "$APP/certs"
  cert_stale "$ip" || return 0
  [ -f "$APP/certs/cert.pem" ] && log "证书过期或本机 IP 变成 $ip 了，重签一张"
  log "生成自签证书（SAN: $ip, localhost, 有效期 $CERT_DAYS 天）"
  # iOS 13+ 对证书有效期有上限（825 天），而且要求 serverAuth 用途；
  # 老参数 -days 3650 不写 EKU，iPhone 勾了信任照样报证书错误。
  openssl req -x509 -newkey rsa:2048 -nodes -days "$CERT_DAYS" \
    -keyout "$APP/certs/key.pem" -out "$APP/certs/cert.pem" \
    -subj "/CN=android-mirror" \
    -addext "subjectAltName=DNS:localhost,IP:127.0.0.1,IP:$ip" \
    -addext "extendedKeyUsage=serverAuth" \
    -addext "keyUsage=digitalSignature,keyEncipherment" >/dev/null 2>&1 \
    || die "openssl 生成证书失败（-addext 需要 openssl >=1.1.1）"
  chmod 600 "$APP/certs/key.pem"
  printf '%s' "$ip" > "$APP/certs/.san_ip"
}

# 把 .env 里的端口写进 ws-scrcpy 的配置：改了 .env 端口才不会门代理到空端口
write_ws_config() {
  cat > "$WSCONF" <<EOF
# generated by run.sh - 别手改，改 .env 后重跑 ./run.sh start
server:
    - secure: false
      port: $UPSTREAM_PORT
EOF
}

setup() {
  need_node
  need_toolchain
  command -v git >/dev/null 2>&1 || die "需要 git"
  if [ ! -d "$WSREPO/.git" ]; then
    log "拉取 ws-scrcpy（上游）"
    git clone --depth 1 https://github.com/NetrisTV/ws-scrcpy.git "$WSREPO" || die "clone 失败"
  fi
  log "安装依赖并构建（几分钟，第一次慢）"
  ( cd "$WSREPO" && npm install --no-audit --no-fund ) || die "npm install 失败（多半是 node-pty 编译失败，见上面的工具链提示）"
  ( cd "$WSREPO" && "$NODE_BIN" -e "require('node-pty')" ) || die "node-pty 没装好：先装 build-essential 再重跑 setup"
  ( cd "$WSREPO" && npm run dist ) || die "构建失败"
  log "构建完成（产物在 $WSREPO/dist）"
  gen_cert
  if [ ! -f "$ENVF" ]; then
    local tok; tok=$(head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 24)
    cat > "$ENVF" <<EOF
UPSTREAM_PORT=$UPSTREAM_PORT
GATE_PORT=$GATE_PORT
GATE_TOKEN=$tok
EOF
    chmod 600 "$ENVF"
    log "已生成访问令牌，写在 $ENVF"
  fi
  write_ws_config
  log "完成。下一步：./web/run.sh start"
}

running() { [ -f "$1" ] && kill -0 "$(cat "$1" 2>/dev/null)" 2>/dev/null; }

# macOS 没有 setsid；没有它也能跑，只是子进程不再是新会话首进程
spawn_bg() {   # spawn_bg <logfile> <cmd...>   把 pid 打到 stdout
  local logf="$1"; shift
  if command -v setsid >/dev/null 2>&1; then
    setsid nohup "$@" >>"$logf" 2>&1 < /dev/null &
  else
    nohup "$@" >>"$logf" 2>&1 < /dev/null &
  fi
  echo $!
}

start() {
  need_node
  [ -f "$ENVF" ] || die "还没 setup，先跑 ./web/run.sh setup"
  # shellcheck disable=SC1090
  set -a; . "$ENVF"; set +a
  mkdir -p "$APP/logs"
  write_ws_config

  if ! running "$APP/.ws.pid"; then
    log "启动 ws-scrcpy :$UPSTREAM_PORT（只绑 127.0.0.1）"
    # --require loopback.js：上游 listen(port) 不带 host 会绑 0.0.0.0，等于把
    # 无鉴权的手机控制面板敞开在局域网上；这个 preload 把它钉在回环。
    # WS_SCRCPY_CONFIG：上游只认这个环境变量，不认 UPSTREAM_PORT。
    ( cd "$WSREPO/dist" || exit 1
      WS_SCRCPY_CONFIG="$WSCONF" spawn_bg "$APP/logs/ws.log" \
        "$NODE_BIN" --require "$APP/loopback.js" index.js > "$APP/.ws.pid" )
    sleep 3
  fi
  if ! running "$APP/.gate.pid"; then
    gen_cert
    log "启动 HTTPS 门 :$GATE_PORT"
    # 令牌走环境变量（.env 已 export），别放命令行：ps aux 能看见参数
    spawn_bg "$APP/logs/gate.log" "$NODE_BIN" "$APP/gate.js" \
      --port "$GATE_PORT" --target "127.0.0.1:$UPSTREAM_PORT" \
      --cert "$APP/certs/cert.pem" --key "$APP/certs/key.pem" > "$APP/.gate.pid"
    sleep 1
  fi
  url
}

stop() {
  for f in "$APP/.gate.pid" "$APP/.ws.pid"; do
    [ -f "$f" ] || continue
    kill "$(cat "$f")" 2>/dev/null && log "停 $(basename "$f") pid=$(cat "$f")"
    rm -f "$f"
  done
}

status() {
  # shellcheck disable=SC1090
  [ -f "$ENVF" ] && { set -a; . "$ENVF"; set +a; }
  running "$APP/.ws.pid"   && log "ws-scrcpy 运行中 pid=$(cat "$APP/.ws.pid")"   || log "ws-scrcpy 未运行"
  running "$APP/.gate.pid" && log "https 门  运行中 pid=$(cat "$APP/.gate.pid")" || log "https 门  未运行"
  if command -v ss >/dev/null 2>&1; then
    ss -ltn 2>/dev/null | grep -q ":$UPSTREAM_PORT " \
      && log "端口 $UPSTREAM_PORT 在监听（应只见 127.0.0.1）" || log "端口 $UPSTREAM_PORT 没有监听"
  fi
  tail -n 3 "$APP/logs/gate.log" 2>/dev/null | sed 's/^/  gate.log | /'
}

url() {
  # shellcheck disable=SC1090
  set -a; . "$ENVF" 2>/dev/null; set +a
  local ip; ip=$(lan_ip)
  printf '\n  iPhone / iPad 打开： https://%s:%s/\n  令牌：%s\n\n' "$ip" "$GATE_PORT" "${GATE_TOKEN:-?}"
}

case "${1:-}" in
  setup)   setup ;;
  start)   start ;;
  stop)    stop ;;
  restart) stop; sleep 1; start ;;
  status)  status ;;
  url)     url ;;
  logs)    tail -n 40 "$APP/logs/"*.log ;;
  *) echo "用法: $0 setup|start|stop|restart|status|url|logs"; exit 2 ;;
esac
